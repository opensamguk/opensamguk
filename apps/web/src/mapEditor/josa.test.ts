import { describe, expect, it } from 'vitest';
import { josa } from './josa';

describe('조사', () => {
  it.each([
    ['업', '이/가', '업이'],
    ['허창', '이/가', '허창이'],
    ['낙양', '으로/로', '낙양으로'],
    ['장안', '와/과', '장안과'],
    ['계', '와/과', '계와'],
    ['서주', '으로/로', '서주로'],
    ['성도', '을/를', '성도를'],
    ['진류', '은/는', '진류는'],
    ['한중', '은/는', '한중은'],
    ['남질', '으로/로', '남질로'],
    ['3', '은/는', '3은'],
    ['9', '은/는', '9는'],
    ['7', '으로/로', '7로'],
  ] as const)('%s + %s', (word, pair, expected) => {
    expect(josa(word, pair)).toBe(expected);
  });
});
