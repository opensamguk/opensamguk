import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { parseRegistry, matchPortraits, type ManualMatch } from './convert';

const root = new URL('../../', import.meta.url);
const registry = parseRegistry(await readFile(new URL('registry.tsv', import.meta.url), 'utf8'));
const { readings } = JSON.parse(await readFile(new URL('hanja-readings.json', import.meta.url), 'utf8')) as {
  readings: Record<string, string>;
};
const scenario = JSON.parse(await readFile(new URL('resources/scenario/1030.json', root), 'utf8')) as {
  general: [number, string, ...unknown[]][];
};
const { matches } = JSON.parse(await readFile(new URL('manual.json', import.meta.url), 'utf8')) as {
  matches: Record<string, ManualMatch>;
};
const result = matchPortraits(
  scenario.general.map((row) => row[1]),
  registry,
  readings,
  matches,
);
const output = {
  $comment:
    'Generated by pnpm portraits:map. Sources and licenses: resources/NOTICE.md. Ambiguous or unmatched names stay null.',
  ...result,
};
await mkdir(new URL('resources/portraits/', root), { recursive: true });
await writeFile(new URL('resources/portraits/rtk14-map.json', root), JSON.stringify(output, null, 2) + '\n');
console.log(` 초상 대응: ${result.stats.matched}/${result.stats.total} (${result.stats.percent}%)`);
console.log(` 동명이인 ${result.ambiguous.length}명: ${result.ambiguous.map((entry) => entry.name).join(', ')}`);
console.log(` 미대응 ${result.unmatched.length}명: ${result.unmatched.join(', ')}`);
if (result.stats.percent < 80) throw new Error('초상 대응률이 목표 80%보다 낮습니다.');
