import { readFile } from 'node:fs/promises';
import { createDb, readPublishedResources } from '../../packages/db/src/index';
import { scenarioSchema } from '../../packages/rules/src/index';
import { hashState } from '../../packages/shared/src/node/hashState';
import { parseRegistry, matchPortraits, type ManualMatch } from './convert';

async function main() {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) throw new Error('DATABASE_URL이 없습니다. pnpm db:init-resources로 게시 자원을 준비하세요.');
  const db = createDb(databaseUrl);
  try {
    const [scenarioResource, publishedMap] = await readPublishedResources(db, [
      { kind: 'SCENARIO', name: '1030', version: 1 },
      { kind: 'PORTRAIT_MAP', name: 'rtk14-map', version: 1 },
    ]);
    const scenario = scenarioSchema.parse(scenarioResource!.content);
    const registry = parseRegistry(await readFile(new URL('registry.tsv', import.meta.url), 'utf8'));
    const { readings } = JSON.parse(await readFile(new URL('hanja-readings.json', import.meta.url), 'utf8')) as {
      readings: Record<string, string>;
    };
    const { matches } = JSON.parse(await readFile(new URL('manual.json', import.meta.url), 'utf8')) as {
      matches: Record<string, ManualMatch>;
    };
    const result = matchPortraits(
      scenario.general.map((row) => row[1]),
      registry,
      readings,
      matches,
    );
    const output = {
      $comment:
        'Generated by pnpm portraits:map. Sources and licenses: resources/NOTICE.md. Ambiguous or unmatched names stay null.',
      ...result,
    };
    console.log(` 초상 대응: ${result.stats.matched}/${result.stats.total} (${result.stats.percent}%)`);
    console.log(` 동명이인 ${result.ambiguous.length}명: ${result.ambiguous.map((entry) => entry.name).join(', ')}`);
    console.log(` 미대응 ${result.unmatched.length}명: ${result.unmatched.join(', ')}`);
    if (result.stats.percent < 80) throw new Error('초상 대응률이 목표 80%보다 낮습니다.');
    if (hashState(output) !== publishedMap!.contentHash) throw new Error('게시 대응표 rtk14-map@1과 다릅니다.');
    console.log('게시 대응표 rtk14-map@1과 같습니다.');
  } finally {
    await db.$disconnect();
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : '초상 대응표 검사에 실패했습니다.');
  process.exitCode = 1;
});
