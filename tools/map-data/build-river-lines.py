"""Build the 3D map river lines (INT-27) from the shipped Natural Earth river vectors.

Run: python tools/map-data/build-river-lines.py
Reads apps/web/src/mapEditor/geodata/natural-earth.json (Natural Earth, public domain), joins its
`M x,y L x,y` segments into polylines in the 1000x700 integration-map coordinates, simplifies them
(Ramer-Douglas-Peucker, 0.4 map units) and writes apps/web/src/map3d/data/rivers.ts.
Only the 3D map imports the output, so the large geodata file stays out of the 3D chunk and the
first-screen bundle keeps only the bounds it already used. Deterministic and offline.
"""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'apps/web/src/mapEditor/geodata/natural-earth.json'
OUT = ROOT / 'apps/web/src/map3d/data/rivers.ts'
TOLERANCE = 0.4
SEGMENT = re.compile(r'M\s*(-?[\d.]+)[ ,](-?[\d.]+)\s*L\s*(-?[\d.]+)[ ,](-?[\d.]+)')


def lines_of(path: str) -> list[list[tuple[float, float]]]:
    lines: list[list[tuple[float, float]]] = []
    for match in SEGMENT.finditer(path):
        start = (float(match[1]), float(match[2]))
        end = (float(match[3]), float(match[4]))
        if lines and abs(lines[-1][-1][0] - start[0]) < 1e-6 and abs(lines[-1][-1][1] - start[1]) < 1e-6:
            lines[-1].append(end)
        else:
            lines.append([start, end])
    return lines


def distance(point, a, b) -> float:
    (px, py), (ax, ay), (bx, by) = point, a, b
    dx, dy = bx - ax, by - ay
    length = dx * dx + dy * dy
    if length == 0:
        return ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / length))
    return ((px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2) ** 0.5


def simplify(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        first, last = stack.pop()
        index, worst = -1, 0.0
        for i in range(first + 1, last):
            d = distance(points[i], points[first], points[last])
            if d > worst:
                index, worst = i, d
        if index >= 0 and worst > TOLERANCE:
            keep[index] = True
            stack.extend([(first, index), (index, last)])
    return [point for point, kept in zip(points, keep) if kept]


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding='utf8'))
    encoded = []
    for river in data['rivers']:
        for line in lines_of(river['path']):
            points = simplify(line)
            if len(points) >= 2:
                encoded.append(' '.join(f'{x:.1f},{y:.1f}' for x, y in points))
    text = ';'.join(encoded)
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        '// Generated by tools/map-data/build-river-lines.py. Do not edit.\n'
        '// Source: Natural Earth river vectors (public domain) in apps/web/src/mapEditor/geodata/natural-earth.json,\n'
        f'// sha256 {digest}. Integration-map coordinates (1000x700); lines are `x,y x,y` joined by `;`.\n'
        f"export const bounds = {json.dumps(data['bounds'])};\nexport const lines = '{text}';\n",
        encoding='utf8',
        newline='\n',
    )
    print(json.dumps({'file': str(OUT.relative_to(ROOT)), 'lines': len(encoded), 'bytes': len(text)}))


if __name__ == '__main__':
    main()
