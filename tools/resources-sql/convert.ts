type ResourceSlot = (typeof RESOURCE_INPUTS)[number]['slot'];
export type ResourceTexts = { [Slot in ResourceSlot]: string };

export const CONTENT_TAG = '$t4_77_content$';
export const BODY_TAG = '$t4_77_init$';

function hasNul(value: unknown): boolean {
  if (typeof value === 'string') return value.includes('\0');
  if (Array.isArray(value)) return value.some(hasNul);
  if (value !== null && typeof value === 'object') {
    return Object.entries(value).some(([key, entry]) => key.includes('\0') || hasNul(entry));
  }
  return false;
}

function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

export function requirePassingReport(report: { status: 'pass' | 'fail' | 'incomplete' }): void {
  if (report.status !== 'pass') throw new Error(`초기화 자원 검증 실패: ${report.status}`);
}

// 원본 전체를 보존한다. 검증 보고의 value는 SQL 내용으로 쓰지 않는다.
export function convertResourcesToSql(input: ResourceTexts, notice: string): string {
  const entries = RESOURCE_INPUTS.map((resource) => {
    const key = `${resource.kind}/${resource.name}/1`;
    const raw = input[resource.slot].replaceAll('\r\n', '\n');
    if (raw.includes(CONTENT_TAG) || raw.includes(BODY_TAG)) {
      throw new Error(`초기화 자원 구분자 충돌: ${key}`);
    }
    let content: unknown;
    try {
      content = JSON.parse(raw);
    } catch {
      throw new Error(`초기화 자원 JSON 오류: ${key}`);
    }
    if (hasNul(content)) throw new Error(`초기화 자원 NUL 문자: ${key}`);
    return { ...resource, key, raw, content };
  });
  const parsed = Object.fromEntries(entries.map((entry) => [entry.slot, entry.content])) as Record<
    ResourceSlot,
    unknown
  >;
  const report = validateWorldResources(parsed);
  try {
    requirePassingReport(report);
  } catch {
    const keys = entries.filter((entry) => report[entry.slot].status !== 'pass').map((entry) => entry.key);
    throw new Error(`초기화 자원 검증 실패: ${keys.join(', ')}`);
  }
  const statements = entries.map((entry) => {
    if (hashState(entry.content) !== entry.contentHash) {
      throw new Error(`초기화 자원 S0 해시 불일치: ${entry.key}`);
    }
    const comment = (entry.content as { $comment?: unknown }).$comment;
    if (typeof comment !== 'string') throw new Error(`초기화 자원 출처 누락: ${entry.key}`);
    const source = literal(`${entry.path}; ${comment}`);
    const kind = literal(entry.kind);
    const name = literal(entry.name);
    const contentHash = literal(entry.contentHash);
    return `  resource_content := ${CONTENT_TAG}${entry.raw}${CONTENT_TAG}::jsonb;
  INSERT INTO "GameResource"
    ("id", "kind", "name", "version", "status", "content", "contentHash", "source", "createdBy", "publishedAt")
  VALUES
    (gen_random_uuid()::text, ${kind}, ${name}, 1, 'PUBLISHED', resource_content, ${contentHash}, ${source}, NULL, now())
  ON CONFLICT ("kind", "name", "version") DO NOTHING;
  IF NOT EXISTS (
    SELECT 1 FROM "GameResource"
    WHERE "kind" = ${kind} AND "name" = ${name} AND "version" = 1
      AND "content" = resource_content AND "contentHash" = ${contentHash}
      AND "status" = 'PUBLISHED' AND "source" = ${source}
  ) THEN
    RAISE EXCEPTION '초기화 자원 충돌: ${entry.key}';
  END IF;`;
  });
  const normalizedNotice = notice.replaceAll('\r\n', '\n');
  if (normalizedNotice.includes('\0')) throw new Error('초기화 자원 출처에 NUL 문자가 있습니다.');
  const header = normalizedNotice
    .split('\n')
    .map((line) => (line ? `-- ${line}` : '--'))
    .join('\n');
  return `-- Generated by tools/resources-sql/generate.ts; source: resources/NOTICE.md.
${header}

DO ${BODY_TAG}
DECLARE
  resource_content jsonb;
BEGIN
${statements.join('\n\n')}
END;
${BODY_TAG};
`;
}
