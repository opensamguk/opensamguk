import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { legacyCheCrewRegionsMatch } from '../../packages/rules/src/world/crewRegions';
import { validateMap, validateUnitSet } from '../../packages/rules/src/world/validate';
import { hashState } from '../../packages/shared/src/node/hashState';
import { immutableResourceStatement } from './convert';

export const LEGACY_MAP_SQL = new URL('../../packages/db/sql/resources-legacy-maps.sql', import.meta.url);
const source = 'core2026 df6c9269fa1e2862418ba9da481c8dd2d758d6c5; MIT (c) 2025 devsam; resources/NOTICE.md';
const mapSources = [
  ['miniche', '9fafc4f3e0dc47f197c24596ec3abd076a68a81b8b4ce88fd45f9f65d4791d76'],
  ['miniche_b', 'e19b0f521f3304b782186260f71c4e74585b2358a9b5f346c22df1942831e4e6'],
  ['miniche_clean', 'bc2a4189e84dd63eccd9d9319d49b4931e79b804dbe04ce168cf1eb9d4b33181'],
] as const;
const unitSetName = 'che-miniche';
export const LEGACY_MAP_BODY_TAG = '$legacy_maps_init$';
export const LEGACY_MAP_CONTENT_TAG = '$legacy_maps_content$';
const root = new URL('../../', import.meta.url);

async function readPinned(path: string, byteHash: string) {
  const bytes = await readFile(new URL(path, root));
  if (createHash('sha256').update(bytes).digest('hex') !== byteHash)
    throw new Error(`원작 자원 해시가 다릅니다: ${path}`);
  const raw = bytes.toString('utf8');
  if (raw.includes(LEGACY_MAP_BODY_TAG) || raw.includes(LEGACY_MAP_CONTENT_TAG))
    throw new Error(`원작 자원의 SQL 구분자 충돌: ${path}`);
  return { raw, content: JSON.parse(raw) as unknown };
}

export async function legacyMapPublications() {
  const unitSet = await readPinned(
    'resources/unitset/che-miniche.json',
    '76bf3eab3528f44bbab7980e2bdf2090414c3a15f3e4abb07afed6095d9b8b84',
  );
  const unit = validateUnitSet(unitSet.content);
  if (unit.status !== 'pass' || unit.value?.id !== unitSetName) throw new Error('소형 지도 병종을 확인하세요.');
  const rows = await Promise.all(
    mapSources.map(async ([name, byteHash]) => {
      const map = await readPinned(`resources/map/${name}.json`, byteHash);
      const report = validateMap(map.content, { scenarios: [] });
      if (
        report.status !== 'pass' ||
        report.value?.id !== name ||
        !legacyCheCrewRegionsMatch(unit.value!, report.value)
      )
        throw new Error(`원작 지도와 병종 조합이 맞지 않습니다: ${name}`);
      return {
        kind: 'MAP' as const,
        name,
        version: 1,
        raw: map.raw,
        contentHash: hashState(map.content),
        source: `resources/map/map_${name}.json; ${source}`,
      };
    }),
  );
  return [
    ...rows,
    {
      kind: 'UNIT_SET' as const,
      name: unitSetName,
      version: 1,
      raw: unitSet.raw,
      contentHash: hashState(unitSet.content),
      source: `resources/unitset/unitset_che.json; ${source}`,
    },
  ];
}

export function legacyMapsSql(rows: Awaited<ReturnType<typeof legacyMapPublications>>): string {
  return [
    '-- Generated by tools/resources-sql/legacy-maps.ts; source: resources/NOTICE.md.',
    'DO ' + LEGACY_MAP_BODY_TAG,
    'DECLARE',
    '  resource_content jsonb;',
    'BEGIN',
    rows.map((row) => immutableResourceStatement(row, LEGACY_MAP_CONTENT_TAG)).join('\n\n'),
    'END;',
    LEGACY_MAP_BODY_TAG + ';',
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(LEGACY_MAP_SQL, legacyMapsSql(await legacyMapPublications()), 'utf8');
}
