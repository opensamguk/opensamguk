export type BuildingKey = (typeof BUILDINGS)[number]['key'];
export const BUILDING_KEYS = BUILDINGS.map((spec) => spec.key);
export const buildingSpec = (key: BuildingKey): BuildingSpec => BUILDINGS.find((spec) => spec.key === key)!;
export const landBuildingSchema = z.strictObject({
  slotId: z.string().min(1),
  building: z.enum(BUILDING_KEYS),
  remainingTurns: z.number().int().min(0).max(2),
  score: z.number().int().min(0).max(450),
});
export const cityLandStateSchema = z.strictObject({
  version: z.literal(1),
  cities: z.record(z.string().regex(/^[1-9]\d*$/), z.array(landBuildingSchema)),
  managed: z.record(z.string(), z.array(z.enum(['agriculture', 'commerce', 'security', 'defence']))),
});
export type CityLandState = z.infer<typeof cityLandStateSchema>;

export function landPopulationBonus(world: Partial<Pick<WorldView, 'campaign'>>, cityKey: number): number {
  return (
    world.campaign?.land?.cities[String(cityKey)]?.reduce(
      (sum, row) => sum + (row.remainingTurns ? 0 : (buildingSpec(row.building).population ?? 0)),
      0,
    ) ?? 0
  );
}
